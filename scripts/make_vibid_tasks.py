"""ViBidLQA questions as direction-B tasks over the vbpl clause units, split by gold article (no context yet).

  python scripts/make_vibid_tasks.py            # data/tasks/vibid_dev.jsonl and vibid_test.jsonl

Only the human-written test file of ViBidLQA is used (1,000 questions); its train file was generated by an LLM
and is kept for training labels. Every question comes with a passage of the Bidding Law 22/2023/QH15 or of
Decree 24/2024/NĐ-CP. The passage names the article ("Điều 66. …") but not always the document, so it is mapped to
the article of the two documents in data/legal/units.jsonl whose text covers ≥ 90% of the passage's syllables. The
gold units are the clause units of that article that contain the extractive answer: the contexts are then built
from vbpl units alone (scripts/legal_rag.py --dataset vibid), and the gold looks like any other unit. Questions
whose passage maps to no article, or whose answer is in no unit of it (another version of the text), are dropped.
Rows: id (vbq-<row of the CSV>), cluster (= gold article, so that dev and test share no gold article), question,
answers ([extractive answer]), abstractive_answer, gold_units ([[unit ids]]), doc_id, article, source_task.
The split is by cluster with a fixed seed; vibid_test is held out (viword.heldout.LEGAL_TEST_FILES).
"""
import argparse
import json
import random
import re
from collections import defaultdict

from viword.legal import normalize

DOCS = ("166581", "166583")  # vbpl ids of Luật Đấu thầu 22/2023/QH15 and Nghị định 24/2024/NĐ-CP
MIN_COVERAGE = 0.9


def norm(text: str) -> str:
    """Lower case, punctuation as spaces, single spaces: the passages and the vbpl text differ in both."""
    return re.sub(r"\s+", " ", re.sub(r"[^\w\s]", " ", normalize(str(text)).lower())).strip()


def article_of(passage: str, units_by_article: dict) -> tuple[str, str] | None:
    """(doc_id, article) of the passage: its "Điều N." in the document whose article text covers it best."""
    m = re.search(r"điều (\d+[a-zđ]?)\.", normalize(passage).lower())
    if not m:
        return None
    words = set(norm(passage).split())
    best, coverage = None, 0.0
    for doc in DOCS:
        units = units_by_article.get((doc, m.group(1)))
        if units:
            c = len(words & set(norm(" ".join(u["text"] for u in units)).split())) / len(words)
            if c > coverage:
                best, coverage = (doc, m.group(1)), c
    return best if coverage >= MIN_COVERAGE else None


def answer_units(answer: str, units: list[dict]) -> list[str]:
    """Ids of the units whose text contains the answer."""
    a = norm(answer)
    return [u["uid"] for u in units if a and a in norm(u["text"])]


def load_units(path: str) -> dict:
    """(doc_id, article) → units of the two documents, in file order (clause order)."""
    by_article = defaultdict(list)
    with open(path, encoding="utf-8") as f:
        for line in f:
            if not any(f'"{d}|' in line for d in DOCS):
                continue
            u = json.loads(line)
            doc, att, art, _ = u["uid"].split("|")
            if doc in DOCS and att == "0":
                by_article[doc, art].append(u)
    return by_article


def main() -> None:
    import pandas as pd

    ap = argparse.ArgumentParser()
    ap.add_argument("--raw", default="data/raw/vibidlqa/ViBiDLQA_test.csv")
    ap.add_argument("--units", default="data/legal/units.jsonl")
    ap.add_argument("--out", default="data/tasks")
    ap.add_argument("--dev-share", type=float, default=0.4)
    ap.add_argument("--seed", type=int, default=0)
    args = ap.parse_args()

    by_article = load_units(args.units)
    rows, dropped = [], defaultdict(int)
    for i, r in pd.read_csv(args.raw).iterrows():
        gold = article_of(r["context"], by_article)
        if gold is None:
            dropped["passage maps to no article"] += 1
            continue
        units = answer_units(r["extractive_answer"], by_article[gold])
        if not units:
            dropped["answer in no unit of the article"] += 1
            continue
        rows.append({"id": f"vbq-{i}", "cluster": f"{gold[0]}|{gold[1]}", "question": str(r["question"]).strip(),
                     "answers": [str(r["extractive_answer"]).strip()],
                     "abstractive_answer": str(r["abstractive_answer"]).strip(), "gold_units": [units],
                     "doc_id": gold[0], "article": gold[1], "source_task": "vibid"})

    clusters = sorted({r["cluster"] for r in rows})
    random.Random(args.seed).shuffle(clusters)
    dev_clusters, n = set(), 0
    for c in clusters:  # take whole clusters until the dev share of questions is reached
        if n >= args.dev_share * len(rows):
            break
        dev_clusters.add(c)
        n += sum(r["cluster"] == c for r in rows)
    for split, keep in (("dev", True), ("test", False)):
        part = [r for r in rows if (r["cluster"] in dev_clusters) == keep]
        with open(f"{args.out}/vibid_{split}.jsonl", "w", encoding="utf-8") as f:
            for r in part:
                f.write(json.dumps(r, ensure_ascii=False) + "\n")
        by_doc = defaultdict(int)
        for r in part:
            by_doc[r["doc_id"]] += 1
        print(f"vibid_{split}: {len(part)} questions {dict(by_doc)}, {len({r['cluster'] for r in part})} articles")
    print("dropped:", dict(dropped))


if __name__ == "__main__":
    main()
